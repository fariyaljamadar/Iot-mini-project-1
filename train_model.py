"""
Edge-AI occupancy model for the Smart Classroom project.

Trains a tiny logistic-regression classifier (pure NumPy) on a synthetic
classroom dataset and exports the weights as a C header so the ESP32 can run
inference locally (no cloud, no ML library on the device).

Features : motion (PIR, 0/1), temperature (C), humidity (%), light (lux)
Label    : 1 = OCCUPIED, 0 = EMPTY

Usage (Google Colab or local):
    pip install numpy
    python train_model.py
Outputs:
    ai/classroom_dataset.csv        - generated training data
    ai/model_metrics.txt            - accuracy / confusion matrix
    firmware/include/model.h        - weights used by the firmware
"""
import csv
import pathlib

import numpy as np

SEED = 42
N_SAMPLES = 4000
FEATURES = ["motion", "temperature", "humidity", "lux"]

HERE = pathlib.Path(__file__).resolve().parent
DATASET_CSV = HERE / "classroom_dataset.csv"
METRICS_TXT = HERE / "model_metrics.txt"
MODEL_H = HERE.parent / "firmware" / "include" / "model.h"


def make_dataset(n, rng):
    """Synthetic classroom data: people raise temp/humidity and trigger the PIR."""
    y = rng.integers(0, 2, n)
    occ = y == 1
    motion = np.where(occ, rng.random(n) < 0.92, rng.random(n) < 0.04).astype(float)
    temp = np.where(occ, rng.normal(28.5, 1.5, n), rng.normal(26.5, 1.8, n))
    hum = np.where(occ, rng.normal(62.0, 5.0, n), rng.normal(55.0, 6.0, n))
    lux = np.where(occ, rng.normal(350, 150, n), rng.normal(250, 180, n)).clip(0, 1000)
    X = np.column_stack([motion, temp, hum, lux])
    return X, y.astype(float)


def sigmoid(z):
    return 1.0 / (1.0 + np.exp(-z))


def train(X, y, lr=0.1, epochs=4000):
    w = np.zeros(X.shape[1])
    b = 0.0
    for _ in range(epochs):
        p = sigmoid(X @ w + b)
        grad_w = X.T @ (p - y) / len(y)
        grad_b = np.mean(p - y)
        w -= lr * grad_w
        b -= lr * grad_b
    return w, b


def main():
    rng = np.random.default_rng(SEED)
    X, y = make_dataset(N_SAMPLES, rng)

    with open(DATASET_CSV, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(FEATURES + ["occupied"])
        for row, label in zip(X, y):
            writer.writerow([int(row[0]), f"{row[1]:.2f}", f"{row[2]:.2f}", f"{row[3]:.1f}", int(label)])

    split = int(0.8 * N_SAMPLES)
    X_train, y_train, X_test, y_test = X[:split], y[:split], X[split:], y[split:]

    mean = X_train.mean(axis=0)
    std = X_train.std(axis=0)
    std[std == 0] = 1.0

    w, b = train((X_train - mean) / std, y_train)

    pred = (sigmoid(((X_test - mean) / std) @ w + b) >= 0.5).astype(float)
    acc = float(np.mean(pred == y_test))
    tp = int(np.sum((pred == 1) & (y_test == 1)))
    tn = int(np.sum((pred == 0) & (y_test == 0)))
    fp = int(np.sum((pred == 1) & (y_test == 0)))
    fn = int(np.sum((pred == 0) & (y_test == 1)))

    report = (
        f"Test accuracy : {acc * 100:.2f} %\n"
        f"Confusion     : TP={tp} TN={tn} FP={fp} FN={fn}\n"
        f"Weights       : {dict(zip(FEATURES, np.round(w, 4).tolist()))}\n"
        f"Bias          : {b:.4f}\n"
        "Note: trained on SYNTHETIC data; accuracy reflects the simulated dataset only.\n"
    )
    print(report)
    METRICS_TXT.write_text(report)

    def arr(values):
        return ", ".join(f"{v:.6f}f" for v in values)

    header = f"""// Auto-generated by ai/train_model.py - do not edit by hand.
// Logistic-regression occupancy model. Feature order: {', '.join(FEATURES)}
#pragma once

#define MODEL_N_FEATURES {len(FEATURES)}

static const float MODEL_MEAN[MODEL_N_FEATURES]    = {{ {arr(mean)} }};
static const float MODEL_STD[MODEL_N_FEATURES]     = {{ {arr(std)} }};
static const float MODEL_WEIGHTS[MODEL_N_FEATURES] = {{ {arr(w)} }};
static const float MODEL_BIAS = {b:.6f}f;
"""
    MODEL_H.write_text(header)
    print(f"Wrote {MODEL_H}")


if __name__ == "__main__":
    main()
